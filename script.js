const langBtn = document.getElementById('lang-toggle');
const themeBtn = document.getElementById('theme-toggle');
const htmlEl = document.documentElement;

let currentLang = localStorage.getItem('lang') || 'en';
let isDark = localStorage.theme === 'dark' || (!('theme' in localStorage) && window.matchMedia('(prefers-color-scheme: dark)').matches);

if (isDark) htmlEl.classList.add('dark');

if(langBtn) {
    langBtn.addEventListener('click', () => {
        currentLang = currentLang === 'en' ? 'ar' : 'en';
        localStorage.setItem('lang', currentLang);
        applyLanguage();
    });
}

if(themeBtn) {
    themeBtn.addEventListener('click', () => {
        isDark = !isDark;
        if (isDark) {
            htmlEl.classList.add('dark');
            localStorage.theme = 'dark';
        } else {
            htmlEl.classList.remove('dark');
            localStorage.theme = 'light';
        }
    });
}

const form = document.getElementById('lead-form');
if(form) {
    form.addEventListener('submit', (e) => {
        e.preventDefault();
        if(form.checkValidity()){
            alert(currentLang === 'en' ? 'Request submitted. Our sales team will be in touch.' : 'تم تقديم الطلب. فريق المبيعات سيتواصل معك.');
            form.reset();
        }
    });
}

function applyLanguage() {
    htmlEl.lang = currentLang;
    htmlEl.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
    
    if(currentLang === 'ar') {
        htmlEl.classList.remove('font-sans');
        htmlEl.classList.add('font-arabic'); 
        document.body.classList.remove('font-sans');
        document.body.classList.add('font-arabic');
    } else {
        htmlEl.classList.remove('font-arabic');
        htmlEl.classList.add('font-sans');
        document.body.classList.remove('font-arabic');
        document.body.classList.add('font-sans');
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if(translations[currentLang] && translations[currentLang][key]) el.innerHTML = translations[currentLang][key];
    });
}

applyLanguage();

const observerOpts = { threshold: 0.1 };
const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.classList.add('show');
        }
    });
}, observerOpts);

document.querySelectorAll('.fade-in').forEach(el => observer.observe(el));
